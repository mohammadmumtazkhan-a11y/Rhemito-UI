export interface Contact {
  id: string;
  email: string; // Unique primary identifier (case-insensitive)
  contactType: "individual" | "business";

  // Role flags
  isSender: boolean;
  isRecipient: boolean;

  // Personal / Business Info
  firstName: string;
  middleName?: string;
  lastName: string;
  businessName?: string;
  countryCode: string;
  phone: string;
  dob?: string;
  country: string;
  currency: string;
  relationship: string;
  createdAt: string;

  // Banking & Payout Info
  bankName: string;
  accountNumber: string;
  sortCode: string; // UK GBP — e.g. "20-45-67"
  iban: string; // EUR / international
  swift: string; // international BIC/SWIFT
  serviceType: string;
  uniqueCode: string; // 6-digit payout identifier
  narration: string; // optional; mandatory for Nigerian beneficiaries
  updatedAt?: string;
}

