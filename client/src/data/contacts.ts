export function contactDisplayName(contact: Contact): string {
  if (contact.contactType === "business") {
    return contact.businessName || "Unnamed Business";
  }
  const parts = [contact.firstName, contact.middleName, contact.lastName].filter(Boolean);
  return parts.join(" ") || "Unnamed Contact";
}

export function toKnownSender(contact: Contact): KnownSender {
  return {
    id: contact.id,
    isRecipient: contact.isRecipient,
    uniqueCode: contact.uniqueCode,
    senderType: contact.contactType,
    firstName: contact.firstName,
    middleName: contact.middleName || "",
    lastName: contact.lastName,
    businessName: contact.businessName || "",
    email: contact.email,
    countryCode: contact.countryCode,
    phone: contact.phone,
    dob: contact.dob || "",
    country: contact.country,
    currency: contact.currency,
    relationship: contact.relationship,
    createdAt: contact.createdAt,
    bankName: contact.bankName,
    accountNumber: contact.accountNumber,
    sortCode: contact.sortCode,
    iban: contact.iban,
    swift: contact.swift,
    narration: contact.narration,
    serviceType: contact.serviceType,
  };
}

export function toKnownRecipient(contact: Contact): KnownRecipient {
  return {
    id: contact.id,
    email: contact.email,
    isSender: contact.isSender,
    recipientType: contact.contactType,
    firstName: contact.firstName,
    lastName: contact.lastName,
    businessName: contact.businessName || "",
    country: contact.country,
    currency: contact.currency,
    bankName: contact.bankName,
    accountNumber: contact.accountNumber,
    sortCode: contact.sortCode,
    iban: contact.iban,
    swift: contact.swift,
    serviceType: contact.serviceType,
    uniqueCode: contact.uniqueCode,
    narration: contact.narration,
    relationship: contact.relationship,
    createdAt: contact.createdAt,
  };
}
